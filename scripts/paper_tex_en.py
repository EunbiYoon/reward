HANGUL = re.compile(r"[가-힣]")


def translate(name: str, text: str) -> str:
    table = {**COMMON, **PER_FILE.get(name, {})}
    out = []
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("%"):   # comments may stay Korean-free anyway; keep them as they are
            out.append(HANGUL.sub("", line) if HANGUL.search(line) else line)
            continue
        for ko in sorted(table, key=len, reverse=True):
            line = line.replace(ko, table[ko])
        out.append(line)
    return "".join(out)


def main():
    bad = []
    for src in sorted(glob.glob(os.path.join(SRC, "*.tex"))):
        name = os.path.basename(src)
        text = translate(name, open(src, encoding="utf-8").read())
        for i, line in enumerate(text.splitlines(), 1):
            if HANGUL.search(line):
                bad.append(f"{name}:{i}: {line.strip()}")
        with open(os.path.join(DST, name), "w", encoding="utf-8") as f:
            f.write(text)
        print("->", os.path.join(DST, name))
    if bad:
        sys.exit("untranslated Korean left (add it to COMMON or PER_FILE):\n" + "\n".join(bad))


if __name__ == "__main__":
    main()
